/**
 * SYNC – Shared Types: Incident
 *
 * An Incident is the core reporting unit. It captures an emergency event
 * created by a device operator. Incidents are propagated across the mesh
 * and may be updated as the situation evolves.
 *
 * Design decisions:
 * - Location is optional because reports may be created by witnesses who
 *   do not have GPS access or who disable location for privacy.
 * - `reporterId` maps to `Device.deviceId` — not a user account ID.
 *   SYNC is designed for pseudonymous device-level identity in Phase 1.
 */

export type IncidentCategory =
  | 'medical'
  | 'fire'
  | 'flood'
  | 'structural_collapse'
  | 'missing_person'
  | 'resource_request'
  | 'security'
  | 'other';

export type IncidentSeverity = 'low' | 'medium' | 'high' | 'critical';

export type IncidentStatus = 'active' | 'resolved' | 'cancelled' | 'stale';

export interface Incident {
  /** UUID — generated by the originating device */
  incidentId: string;

  category: IncidentCategory;
  severity: IncidentSeverity;

  /** Free-form description of the emergency situation */
  description: string;

  /**
   * GPS coordinates. Optional — see file header for rationale.
   * Stored in decimal degrees (WGS-84).
   */
  latitude?: number;
  longitude?: number;

  /** ISO 8601 — set by the originating device at creation time */
  createdAt: string;

  /** ISO 8601 — updated whenever any peer applies a delta to this incident */
  updatedAt: string;

  status: IncidentStatus;

  /** Device UUID of the first reporter */
  reporterId: string;
}

