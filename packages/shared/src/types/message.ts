/**
 * SYNC – Shared Types: Message
 *
 * A Message is the network transport unit. It wraps arbitrary JSON payloads
 * and carries routing metadata for the store-carry-forward mesh.
 *
 * Key design decisions:
 * - `hopCount` / `maxHops` implement a simple TTL at the routing layer.
 *   Each relay increments `hopCount`. Devices refuse to forward if
 *   hopCount >= maxHops. This prevents unbounded propagation.
 * - `expiresAt` provides a wall-clock TTL independent of hop count.
 *   Devices discard expired messages and do not forward them.
 * - `recipientId` is optional — null means broadcast to all reachable peers.
 * - `payload` is a string-encoded JSON object. Keeping it opaque at this
 *   layer allows the protocol to carry any structured data without
 *   deserializing it at every intermediate hop.
 */

export type MessagePriority = 'low' | 'normal' | 'high' | 'critical';

export type MessageStatus =
  | 'pending'      // created locally, not yet sent
  | 'sent'         // handed off to at least one peer
  | 'delivered'    // confirmed received by intended recipient(s)
  | 'failed'       // could not be delivered within TTL / hop limit
  | 'expired';     // wall-clock TTL exceeded

export interface Message {
  /** UUID — generated by the originating device */
  messageId: string;

  /** Links the message to an incident, if applicable. Null = standalone message */
  incidentId: string | null;

  /** Device UUID of the originator */
  senderId: string;

  /**
   * Intended recipient device UUID.
   * Null = broadcast — any SYNC device that receives it should store and forward.
   */
  recipientId: string | null;

  /**
   * JSON-encoded string payload.
   * The schema of this payload depends on the message context (incident update,
   * resource request, acknowledgement, etc.). Encoded as a string so intermediate
   * relay nodes do not need to understand the payload structure.
   */
  payload: string;

  priority: MessagePriority;

  /** ISO 8601 — creation timestamp on the originating device */
  createdAt: string;

  /**
   * ISO 8601 — wall-clock expiry.
   * After this time, devices MUST NOT forward the message and SHOULD discard it.
   * Recommended default: createdAt + 24 hours for critical, + 6 hours for normal.
   */
  expiresAt: string;

  /**
   * Number of times this message has been relayed by intermediate devices.
   * Starts at 0 on the originating device.
   */
  hopCount: number;

  /**
   * Maximum number of relay hops permitted.
   * Default value: see constants/protocol.ts
   */
  maxHops: number;

  messageStatus: MessageStatus;
}

